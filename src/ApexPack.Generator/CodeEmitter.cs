using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace ApexPack.Generator;

/// <summary>
/// <see cref="TypeModel"/> から C# を出力する。ワイヤ形式は docs/WireFormat.md と一致させること。
/// </summary>
internal sealed class CodeEmitter
{
    private const string Ns = "global::ApexPack.";
    private const string Ext = "__ApexExt";
    private const string Wire = "__ApexWire";
    private const string Un = "__ApexUnsafe";

    private const string WriterConstraints =
        "        where TWriter : struct, global::ApexPack.Buffers.IApexBufferWriter, allows ref struct\n" +
        "        where TTracker : global::ApexPack.IReferenceTracker, allows ref struct";

    private const string ReaderConstraints =
        "        where TReader : struct, global::ApexPack.Buffers.IApexBufferReader, allows ref struct\n" +
        "        where TTracker : global::ApexPack.IReferenceTracker, allows ref struct\n" +
        "        where TGuard : global::ApexPack.ISecurityGuard, allows ref struct";

    private readonly StringBuilder _sb = new();
    private int _indent;
    private readonly TypeModel _m;

    private CodeEmitter(TypeModel model) => _m = model;

    public static string Emit(TypeModel model)
    {
        var emitter = new CodeEmitter(model);
        emitter.EmitFile();
        return emitter._sb.ToString();
    }

    private void L(string line = "")
    {
        if (line.Length == 0)
        {
            _sb.Append('\n');
            return;
        }
        _sb.Append(' ', _indent * 4).Append(line).Append('\n');
    }

    private void Raw(string text) => _sb.Append(text).Append('\n');

    private void Open(string line)
    {
        if (line.Length > 0) L(line);
        L("{");
        _indent++;
    }

    private void Close(string suffix = "")
    {
        _indent--;
        L("}" + suffix);
    }

    // ====================================================================

    private void EmitFile()
    {
        L("// <auto-generated> ApexPack.Generator </auto-generated>");
        L("#nullable enable annotations");
        L("#nullable disable warnings");
        L("#pragma warning disable CS0108, CS0612, CS0618, CS8669");
        L($"using {Ext} = global::ApexPack.Buffers.ApexBufferExtensions;");
        L($"using {Wire} = global::ApexPack.Buffers.ApexWire;");
        L($"using {Un} = global::System.Runtime.CompilerServices.Unsafe;");
        L();

        var symbol = _m.Symbol;
        bool hasNamespace = !symbol.ContainingNamespace.IsGlobalNamespace;
        if (hasNamespace) Open($"namespace {symbol.ContainingNamespace.ToDisplayString()}");

        var containers = new List<INamedTypeSymbol>();
        for (var c = symbol.ContainingType; c is not null; c = c.ContainingType) containers.Insert(0, c);
        foreach (var c in containers) Open($"partial {Keyword(c)} {SelfName(c)}");

        string header = $"partial {Keyword(symbol)} {_m.SelfName} : {Ns}ISerializePackable<{_m.SelfName}>";
        Open(header);

        switch (_m.Kind)
        {
            case PackKind.Union:
                EmitUnion();
                break;
            case PackKind.FixedStruct:
                EmitForwarders();
                EmitFixedStruct();
                break;
            case PackKind.Collection:
                EmitForwarders();
                EmitCollection();
                break;
            default:
                EmitForwarders();
                EmitObject();
                break;
        }

        Close();
        foreach (var _ in containers) Close();
        if (hasNamespace) Close();
    }

    private static string SelfName(INamedTypeSymbol symbol)
        => symbol.TypeParameters.Length == 0
            ? TypeAnalyzer.EscapeIdentifier(symbol.Name)
            : $"{TypeAnalyzer.EscapeIdentifier(symbol.Name)}<{string.Join(", ", symbol.TypeParameters.Select(t => t.Name))}>";

    private static string Keyword(INamedTypeSymbol symbol)
    {
        if (symbol.TypeKind == TypeKind.Interface) return "interface";
        if (symbol.TypeKind == TypeKind.Struct) return symbol.IsRecord ? "record struct" : "struct";
        return symbol.IsRecord ? "record" : "class";
    }


    // ====================================================================
    // 共通の入口(ISerializePackable の便宜メソッドを型名から呼べるようにする)
    // ====================================================================

    private void EmitForwarders()
    {
        string t = _m.SelfName;
        L("[global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
        L($"public static void Serialize<TWriter>(ref TWriter writer, scoped in {t} value)");
        L("    where TWriter : struct, global::ApexPack.Buffers.IApexBufferWriter, allows ref struct");
        Open("");
        L($"var tracker = new {Ns}NullReferenceTracker();");
        L("SerializeWithTracker(ref writer, in value, ref tracker);");
        Close();
        L();
        L("[global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
        L($"public static void Deserialize<TReader>(ref TReader reader, scoped out {t} value)");
        L("    where TReader : struct, global::ApexPack.Buffers.IApexBufferReader, allows ref struct");
        Open("");
        L($"var tracker = new {Ns}NullReferenceTracker();");
        L($"var guard = new {Ns}TrustedSecurityGuard();");
        L("DeserializeGuarded(ref reader, out value, ref tracker, ref guard);");
        Close();
        L();
        L("[global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
        L($"public static void DeserializeWithTracker<TReader, TTracker>(ref TReader reader, scoped out {t} value, ref TTracker tracker)");
        L("    where TReader : struct, global::ApexPack.Buffers.IApexBufferReader, allows ref struct");
        L("    where TTracker : global::ApexPack.IReferenceTracker, allows ref struct");
        Open("");
        L($"var guard = new {Ns}TrustedSecurityGuard();");
        L("DeserializeGuarded(ref reader, out value, ref tracker, ref guard);");
        Close();
        L();
        if (_m.PreserveReferences)
        {
            L($"public static {(_m.HidesBasePreserveReferences ? "new " : "")}bool ApexPreserveReferences => true;");
            L();
        }
    }

    private void SignatureWrite(string name, string valueModifier = "scoped in ", string access = "public static ")
    {
        L($"{access}void {name}<TWriter, TTracker>(ref TWriter writer, {valueModifier}{_m.SelfName} value, ref TTracker tracker)");
        Raw(Indent(WriterConstraints));
    }

    private void SignatureRead(string name)
    {
        L($"public static void {name}<TReader, TTracker, TGuard>(ref TReader reader, scoped out {_m.SelfName} value, ref TTracker tracker, ref TGuard guard)");
        Raw(Indent(ReaderConstraints));
    }

    private string Indent(string constraints)
    {
        string pad = new string(' ', (_indent - 1) * 4);
        return string.Join("\n", constraints.Split('\n').Select(l => pad + l));
    }

    // ====================================================================
    // Union
    // ====================================================================

    private void EmitUnion()
    {
        string t = _m.SelfName;
        bool iface = _m.IsInterface;

        // 実装本体(インターフェースでも private static なら制約を書ける)
        L($"private static void __ApexUnionWrite<TWriter, TTracker>(ref TWriter writer, {t} value, ref TTracker tracker, bool nonNull)");
        Raw(Indent(WriterConstraints));
        Open("");
        Open("switch (value)");
        L("case null:");
        L($"    if (nonNull) {Ns}ApexThrowHelper.ThrowNullNotAllowed(typeof({t}));");
        L($"    {Ext}.WriteByte(ref writer, 0);");
        L("    return;");
        int i = 0;
        foreach (var c in _m.UnionCases)
        {
            L($"case {c.TypeName} __v{i}:");
            L($"    {Ext}.WriteCompactUInt(ref writer, {c.Tag + 1}u);");
            L($"    {Ns}PackableNonNullFormatter<{c.TypeName}>.Write(ref writer, in __v{i}, ref tracker);");
            L("    return;");
            i++;
        }
        L("default:");
        L($"    {Ns}ApexThrowHelper.ThrowUnregisteredUnionType(value.GetType(), typeof({t}));");
        L("    return;");
        Close();
        Close();
        L();

        L($"private static {t} __ApexUnionRead<TReader, TTracker, TGuard>(ref TReader reader, ref TTracker tracker, ref TGuard guard)");
        Raw(Indent(ReaderConstraints));
        Open("");
        L($"uint __tag = {Ext}.ReadCompactUInt(ref reader);");
        Open("switch (__tag)");
        L("case 0u:");
        L("    return default!;");
        foreach (var c in _m.UnionCases)
        {
            L($"case {c.Tag + 1}u:");
            L($"    return {Ns}PackableNonNullFormatter<{c.TypeName}>.Read(ref reader, ref tracker, ref guard);");
        }
        L("default:");
        L($"    {Ns}ApexThrowHelper.ThrowInvalidUnionTag(__tag, typeof({t}));");
        L("    return default!;");
        Close();
        Close();
        L();

        if (iface)
        {
            string prefix = $"static void {Ns}ISerializePackable<{t}>.";
            L($"{prefix}SerializeWithTracker<TWriter, TTracker>(ref TWriter writer, scoped in {t} value, ref TTracker tracker)");
            L("    => __ApexUnionWrite(ref writer, value, ref tracker, false);");
            L();
            L($"{prefix}SerializeNonNull<TWriter, TTracker>(ref TWriter writer, scoped in {t} value, ref TTracker tracker)");
            L("    => __ApexUnionWrite(ref writer, value, ref tracker, true);");
            L();
            L($"{prefix}DeserializeGuarded<TReader, TTracker, TGuard>(ref TReader reader, scoped out {t} value, ref TTracker tracker, ref TGuard guard)");
            L("    => value = __ApexUnionRead(ref reader, ref tracker, ref guard);");
            L();
            L($"{prefix}DeserializeNonNull<TReader, TTracker, TGuard>(ref TReader reader, scoped out {t} value, ref TTracker tracker, ref TGuard guard)");
            L("    => value = __ApexUnionRead(ref reader, ref tracker, ref guard);");
            return;
        }

        EmitForwarders();
        SignatureWrite("SerializeWithTracker");
        L("    => __ApexUnionWrite(ref writer, value, ref tracker, false);");
        L();
        SignatureWrite("SerializeNonNull");
        L("    => __ApexUnionWrite(ref writer, value, ref tracker, true);");
        L();
        SignatureRead("DeserializeGuarded");
        L("    => value = __ApexUnionRead(ref reader, ref tracker, ref guard);");
        L();
        SignatureRead("DeserializeNonNull");
        L("    => value = __ApexUnionRead(ref reader, ref tracker, ref guard);");
    }

    // ====================================================================
    // Collection
    // ====================================================================

    private void EmitCollection()
    {
        string t = _m.SelfName;
        string e = _m.CollectionElement;
        string f = _m.CollectionElementFormatter;

        SignatureWrite("SerializeWithTracker");
        Open("");
        L($"if (value is null) {{ {Ext}.WriteNullCollectionHeader(ref writer); return; }}");
        L($"{Ns}ApexSequence.WriteCollection<TWriter, TTracker, {e}, {f}>(ref writer, value, ref tracker);");
        Close();
        L();
        SignatureRead("DeserializeGuarded");
        Open("");
        L($"int __n = {Ns}ApexSequence.ReadCount<TReader, TGuard, {e}, {f}>(ref reader, ref guard);");
        L("if (__n < 0) { value = default!; return; }");
        L($"var __c = new {t}();");
        L($"for (int __i = 0; __i < __n; __i++) __c.Add({f}.Read(ref reader, ref tracker, ref guard));");
        L("value = __c;");
        Close();
    }

    // ====================================================================
    // FixedStruct
    // ====================================================================

    private void EmitFixedStruct()
    {
        string t = _m.SelfName;
        int n = _m.FixedBytes;

        string raw = _m.FixedRawEligible
            ? string.Join(" && ", new[] { "global::System.BitConverter.IsLittleEndian", $"{Un}.SizeOf<{t}>() == {n}" }.Concat(_m.FixedRawConditions))
            : "false";

        L($"public static int ApexFixedSize => {n};");
        L();
        L($"public static bool ApexIsRawLayout => {raw};");
        L();
        L($"public static int ApexMinBodySize => {n};");
        L();

        L("[global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
        Open($"public static void WriteFixed(ref byte destination, scoped in {t} value, bool littleEndian)");
        if (_m.FixedRawEligible)
        {
            L($"if (littleEndian && ApexIsRawLayout) {{ {Un}.WriteUnaligned(ref destination, value); return; }}");
        }
        int offset = 0;
        foreach (var m in _m.Members)
        {
            L(WriteFixedValue(m.Fixed!, $"ref {Un}.Add(ref destination, {offset})", $"value.{Esc(m.Name)}", "littleEndian"));
            offset += m.Fixed!.Size;
        }
        Close();
        L();

        L("[global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
        Open($"public static {t} ReadFixed(ref readonly byte source, bool littleEndian)");
        if (_m.FixedRawEligible)
        {
            L($"if (littleEndian && ApexIsRawLayout) return {Un}.ReadUnaligned<{t}>(in source);");
        }
        offset = 0;
        foreach (var m in _m.Members)
        {
            L($"var {m.Local} = {ReadFixedValue(m.Fixed!, $"in {Un}.Add(ref {Un}.AsRef(in source), {offset})", "littleEndian")};");
            offset += m.Fixed!.Size;
        }
        L($"return {Construct()};");
        Close();
        L();

        L("[global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
        SignatureWrite("SerializeWithTracker");
        L($"    => WriteFixed(ref writer.GetSpanRef({n}), in value, TWriter.IsHostLittleEndian);");
        L();
        L("[global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
        SignatureRead("DeserializeGuarded");
        L($"    => value = ReadFixed(in reader.GetSpanRef({n}), TReader.IsHostLittleEndian);");
    }

    private static string WriteFixedValue(FixedInfo info, string target, string value, string le)
        => info.IsPackable
            ? $"{info.TypeName}.WriteFixed({target}, {value}, {le});"
            : $"{Wire}.Write<{info.TypeName}>({target}, {value}, {le});";

    private static string ReadFixedValue(FixedInfo info, string source, string le)
        => info.IsPackable
            ? $"{info.TypeName}.ReadFixed({source}, {le})"
            : $"{Wire}.Read<{info.TypeName}>({source}, {le})";

    private static string Esc(string name) => TypeAnalyzer.EscapeIdentifier(name);

    /// <summary>ローカル変数からインスタンスを組み立てる式。</summary>
    private string Construct()
    {
        string t = _m.SelfName;
        var initializers = _m.Members
            .Where(m => m.CtorParameterIndex < 0)
            .Select(m => $"{Esc(m.Name)} = {m.Local}")
            .ToList();
        string args = string.Join(", ", _m.ConstructorArguments.Select(m => m!.Local));
        string init = initializers.Count > 0 ? " { " + string.Join(", ", initializers) + " }" : "";
        if (_m.Constructor is null && initializers.Count > 0) return $"new {t}{init}";
        return $"new {t}({args}){init}";
    }

    // ====================================================================
    // Object
    // ====================================================================

    private bool IsClass => !_m.IsValueType;

    private void EmitObject()
    {
        string t = _m.SelfName;
        L($"public static {(_m.HidesBaseMinBodySize ? "new " : "")}int ApexMinBodySize => {_m.MinBodySize};");
        L();

        if (IsClass)
        {
            SignatureWrite("SerializeWithTracker");
            Open("");
            Open("if (TTracker.IsTrackingEnabled)");
            L($"if ({Ns}ApexReferenceHeader.Write(ref writer, value, ref tracker)) __ApexWriteBody(ref writer, value, ref tracker);");
            L("return;");
            Close();
            L($"if (value is null) {{ {Ext}.WriteByte(ref writer, 0); return; }}");
            if (!_m.HasMarkerBit) L($"{Ext}.WriteByte(ref writer, 1);");
            L("__ApexWriteBody(ref writer, value, ref tracker);");
            Close();
            L();

            SignatureWrite("SerializeNonNull");
            Open("");
            L("if (TTracker.IsTrackingEnabled) { SerializeWithTracker(ref writer, in value, ref tracker); return; }");
            L($"if (value is null) {Ns}ApexThrowHelper.ThrowNullNotAllowed(typeof({t}));");
            L("__ApexWriteBody(ref writer, value, ref tracker);");
            Close();
            L();

            SignatureRead("DeserializeGuarded");
            Open("");
            Open("if (TTracker.IsTrackingEnabled)");
            L($"if ({Ns}ApexReferenceHeader.Read(ref reader, ref tracker, out uint __id, out object? __existing)) value = __ApexReadBody(ref reader, ref tracker, ref guard, __id, true);");
            L($"else value = ({t})__existing!;");
            L("return;");
            Close();
            if (_m.HasMarkerBit)
            {
                L("if (reader.PeekByte() == 0) { _ = reader.GetSpanRef(1); value = null!; return; }");
            }
            else
            {
                L("if (reader.GetSpanRef(1) == 0) { value = null!; return; }");
            }
            L("value = __ApexReadBody(ref reader, ref tracker, ref guard, 0, false);");
            Close();
            L();

            SignatureRead("DeserializeNonNull");
            Open("");
            L("if (TTracker.IsTrackingEnabled) { DeserializeGuarded(ref reader, out value, ref tracker, ref guard); return; }");
            L("value = __ApexReadBody(ref reader, ref tracker, ref guard, 0, false);");
            Close();
            L();

            SignatureWrite("__ApexWriteBody", valueModifier: "", access: "private static ");
        }
        else
        {
            L("[global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
            SignatureWrite("SerializeWithTracker");
            L("    => __ApexWriteBody(ref writer, in value, ref tracker);");
            L();
            L("[global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
            SignatureRead("DeserializeGuarded");
            L("    => value = __ApexReadBody(ref reader, ref tracker, ref guard, 0, false);");
            L();
            SignatureWrite("__ApexWriteBody", access: "private static ");
        }

        Open("");
        EmitWriteBody();
        Close();
        L();

        L($"private static {t} __ApexReadBody<TReader, TTracker, TGuard>(ref TReader reader, ref TTracker tracker, ref TGuard guard, uint __refId, bool __register)");
        Raw(Indent(ReaderConstraints));
        Open("");
        EmitReadBody();
        Close();
    }

    private IEnumerable<MemberModel> BitMembers => _m.Members.Where(m => m.Bit >= 0);
    private IEnumerable<MemberModel> FixedMembers => _m.Members.Where(m => m.Encoding == MemberEncoding.Fixed);
    private IEnumerable<MemberModel> NullableFixedMembers => _m.Members.Where(m => m.Encoding == MemberEncoding.NullableFixed);

    private IEnumerable<MemberModel> VariableMembers => _m.Members.Where(m =>
        m.Encoding is MemberEncoding.Variable or MemberEncoding.NullableVariable or MemberEncoding.InlineCollection);

    private static string BitTest(MemberModel m)
        => m.BitGuarded ? $"{m.Local} is not null"
            : m.Encoding == MemberEncoding.BoolBit ? m.Local
            : $"{m.Local}.HasValue";

    private void EmitWriteBody()
    {
        foreach (var c in _m.OnSerializing) L(c.IsStatic ? $"{c.Name}();" : $"value.{c.Name}();");

        if (_m.Members.Count > 0 || _m.HasMarkerBit) L("bool __le = TWriter.IsHostLittleEndian;");
        foreach (var m in _m.Members)
        {
            L($"var {m.Local} = value.{Esc(m.Name)};");
        }

        // マスク(64 ビットごとのワード)
        int words = (_m.MaskBits + 63) / 64;
        for (int w = 0; w < words; w++)
        {
            var terms = new List<string>();
            if (w == 0 && _m.HasMarkerBit) terms.Add("1UL");
            foreach (var m in BitMembers.Where(b => b.Bit / 64 == w))
            {
                terms.Add($"(({BitTest(m)}) ? {1UL << (m.Bit % 64)}UL : 0UL)");
            }
            L($"ulong __mask{w} = {(terms.Count == 0 ? "0UL" : string.Join(" | ", terms))};");
        }

        int region = _m.MaskBytes + _m.FixedBytes + _m.NullableFixedMaxBytes;
        if (region > 0)
        {
            L($"ref byte __p = ref writer.Reserve({region});");
            for (int b = 0; b < _m.MaskBytes; b++)
            {
                L($"{Un}.Add(ref __p, {b}) = (byte)(__mask{b / 8} >> {(b % 8) * 8});");
            }
            int offset = _m.MaskBytes;
            foreach (var m in FixedMembers)
            {
                L(WriteFixedValue(m.Fixed!, $"ref {Un}.Add(ref __p, {offset})", m.Local, "__le"));
                offset += m.Fixed!.Size;
            }
            if (NullableFixedMembers.Any())
            {
                L($"int __o = {offset};");
                foreach (var m in NullableFixedMembers)
                {
                    // 値は常に現在位置へ書き、値があるときだけ位置を進める(分岐なし)
                    L(WriteFixedValue(m.Fixed!, $"ref {Un}.Add(ref __p, __o)", $"{m.Local}.GetValueOrDefault()", "__le"));
                    L($"__o += {m.Local}.HasValue ? {m.Fixed!.Size} : 0;");
                }
                L("writer.Advance(__o);");
            }
            else
            {
                L($"writer.Advance({offset});");
            }
        }

        foreach (var m in VariableMembers)
        {
            switch (m.Encoding)
            {
                case MemberEncoding.Variable:
                    L($"{(m.BitGuarded ? $"if ({m.Local} is not null) " : "")}{m.Formatter}.Write(ref writer, in {m.Local}, ref tracker);");
                    break;
                case MemberEncoding.NullableVariable:
                    Open($"if ({m.Local}.HasValue)");
                    L($"var {m.Local}v = {m.Local}.GetValueOrDefault();");
                    L($"{m.Formatter}.Write(ref writer, in {m.Local}v, ref tracker);");
                    Close();
                    break;
                case MemberEncoding.InlineCollection:
                    if (m.BitGuarded) Open($"if ({m.Local} is not null)");
                    EmitInlineWrite(m);
                    if (m.BitGuarded) Close();
                    break;
            }
        }

        foreach (var c in _m.OnSerialized) L(c.IsStatic ? $"{c.Name}();" : $"value.{c.Name}();");
    }

    private void EmitInlineWrite(MemberModel m)
    {
        L($"if ({m.Local} is null) {Ext}.WriteNullCollectionHeader(ref writer);");
        Open("else");
        L(m.InlineIsList
            ? $"var {m.Local}s = global::System.Runtime.InteropServices.CollectionsMarshal.AsSpan({m.Local});"
            : $"global::System.ReadOnlySpan<{m.InlineElement}> {m.Local}s = {m.Local};");
        L($"{Ext}.WriteCollectionHeader(ref writer, {m.Local}s.Length);");
        L($"for (int __i = 0; __i < {m.Local}s.Length; __i++) {m.Formatter}.Write(ref writer, in {m.Local}s[__i], ref tracker);");
        Close();
    }

    private string MaskTest(MemberModel m) => $"(__mask{m.Bit / 64} & {1UL << (m.Bit % 64)}UL) != 0UL";

    private void EmitReadBody()
    {
        string t = _m.SelfName;
        foreach (var c in _m.OnDeserializing.Where(c => c.IsStatic)) L($"{c.Name}();");
        if (IsClass) L("guard.EnterDepth();");

        if (_m.CreateEarly)
        {
            L($"var __instance = new {t}();");
            L("if (TTracker.IsTrackingEnabled && __register) tracker.Register(__instance, __refId);");
            foreach (var c in _m.OnDeserializing.Where(c => !c.IsStatic)) L($"__instance.{c.Name}();");
        }

        if (_m.Members.Count > 0) L("bool __le = TReader.IsHostLittleEndian;");

        int head = _m.MaskBytes + _m.FixedBytes;
        if (head > 0)
        {
            L($"ref readonly byte __p = ref reader.GetSpanRef({head});");
            int words = (_m.MaskBits + 63) / 64;
            for (int w = 0; w < words; w++)
            {
                int first = w * 8;
                int count = Math.Min(8, _m.MaskBytes - first);
                var parts = Enumerable.Range(0, count)
                    .Select(i => $"((ulong){Un}.Add(ref {Un}.AsRef(in __p), {first + i}) << {i * 8})");
                L($"ulong __mask{w} = {string.Join(" | ", parts)};");
            }
            int offset = _m.MaskBytes;
            foreach (var m in FixedMembers)
            {
                L($"var {m.Local} = {ReadFixedValue(m.Fixed!, $"in {Un}.Add(ref {Un}.AsRef(in __p), {offset})", "__le")};");
                offset += m.Fixed!.Size;
            }
        }

        foreach (var m in _m.Members.Where(x => x.Encoding == MemberEncoding.BoolBit))
        {
            L($"bool {m.Local} = {MaskTest(m)};");
        }

        var nullableFixed = NullableFixedMembers.ToList();
        if (nullableFixed.Count > 0)
        {
            var sizes = nullableFixed.Select(m => $"(({MaskTest(m)}) ? {m.Fixed!.Size} : 0)");
            L($"ref readonly byte __q = ref reader.GetSpanRef({string.Join(" + ", sizes)});");
            L("int __o = 0;");
            foreach (var m in nullableFixed)
            {
                L($"{m.Fixed!.TypeName}? {m.Local} = null;");
                L($"if ({MaskTest(m)}) {{ {m.Local} = {ReadFixedValue(m.Fixed!, $"in {Un}.Add(ref {Un}.AsRef(in __q), __o)", "__le")}; __o += {m.Fixed!.Size}; }}");
            }
        }

        foreach (var m in VariableMembers)
        {
            switch (m.Encoding)
            {
                case MemberEncoding.Variable when m.BitGuarded:
                    L($"{m.TypeName} {m.Local} = default!;");
                    L($"if ({MaskTest(m)}) {m.Local} = {m.Formatter}.Read(ref reader, ref tracker, ref guard);");
                    break;
                case MemberEncoding.Variable:
                    L($"{m.TypeName} {m.Local} = {m.Formatter}.Read(ref reader, ref tracker, ref guard);");
                    break;
                case MemberEncoding.NullableVariable:
                    L($"{m.TypeName} {m.Local} = null;");
                    L($"if ({MaskTest(m)}) {m.Local} = {m.Formatter}.Read(ref reader, ref tracker, ref guard);");
                    break;
                case MemberEncoding.InlineCollection:
                    EmitInlineRead(m);
                    break;
            }
        }

        if (_m.CreateEarly)
        {
            foreach (var m in _m.Members) L($"__instance.{Esc(m.Name)} = {m.Local};");
        }
        else
        {
            L($"var __instance = {Construct()};");
            if (IsClass) L("if (TTracker.IsTrackingEnabled && __register) tracker.Register(__instance, __refId);");
        }

        foreach (var c in _m.OnDeserialized) L(c.IsStatic ? $"{c.Name}();" : $"__instance.{c.Name}();");
        if (IsClass) L("guard.ExitDepth();");
        L("return __instance;");
    }

    private void EmitInlineRead(MemberModel m)
    {
        string e = m.InlineElement;
        L($"{m.TypeName} {m.Local} = null;");
        Open(m.BitGuarded ? $"if ({MaskTest(m)})" : "");
        L($"int __n = {Ext}.ReadCollectionHeader(ref reader, ref guard, {m.Formatter}.MinWireSize);");
        L($"if (__n < 0) {m.Local} = null;");
        Open("else");
        if (m.InlineIsList)
        {
            L($"var __l = new global::System.Collections.Generic.List<{e}>(__n);");
            L("global::System.Runtime.InteropServices.CollectionsMarshal.SetCount(__l, __n);");
            L("var __s = global::System.Runtime.InteropServices.CollectionsMarshal.AsSpan(__l);");
            L($"for (int __i = 0; __i < __s.Length; __i++) __s[__i] = {m.Formatter}.Read(ref reader, ref tracker, ref guard);");
            L($"{m.Local} = __l;");
        }
        else
        {
            L($"var __a = __n == 0 ? global::System.Array.Empty<{e}>() : new {e}[__n];");
            L($"for (int __i = 0; __i < __a.Length; __i++) __a[__i] = {m.Formatter}.Read(ref reader, ref tracker, ref guard);");
            L($"{m.Local} = __a;");
        }
        Close();
        Close();
    }
