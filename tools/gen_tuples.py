import sys
W = """        where TWriter : struct, IApexBufferWriter, allows ref struct
        where TTracker : IReferenceTracker, allows ref struct"""
R = """        where TReader : struct, IApexBufferReader, allows ref struct
        where TTracker : IReferenceTracker, allows ref struct
        where TGuard : ISecurityGuard, allows ref struct"""
out = ["// <auto-generated> tools/gen_tuples.py で生成。手で編集しない </auto-generated>",
"#nullable enable", "using System;", "using System.Runtime.CompilerServices;", "using System.Runtime.InteropServices;", "using ApexPack.Buffers;", "", "namespace ApexPack;", ""]
def names(n, rest):
    ts = [f"T{i}" for i in range(1, n+1)]
    if rest: ts.append("TRest")
    return ts
for n in range(1, 9):
    for kind in ("ValueTuple", "Tuple"):
        rest = n == 8
        ts = names(7 if rest else n, rest)
        fs = [f"F{i}" for i in range(1, len(ts)+1)]
        tt = f"{kind}<{', '.join(ts)}>"
        target = tt if kind == "ValueTuple" else tt + "?"
        gen = ", ".join(ts + fs)
        cons = "\n".join(f"    where {f} : IApexFormatter<{t}>" for t, f in zip(ts, fs))
        if rest and kind == "ValueTuple":
            cons += "\n    where TRest : struct"
        if rest and kind == "Tuple":
            cons += "\n    where TRest : notnull"
        items = [f"Item{i}" for i in range(1, len(ts))] + (["Rest"] if rest else [f"Item{len(ts)}"])
        out.append(f"/// <summary>{kind}（{len(ts)} 要素）。</summary>")
        out.append(f"public readonly struct {kind}Formatter<{gen}> : IApexFormatter<{target}>")
        out.append(cons)
        out.append("{")
        out.append("    [MethodImpl(MethodImplOptions.AggressiveInlining)]")
        out.append(f"    public static void Write<TWriter, TTracker>(ref TWriter writer, scoped in {target} value, ref TTracker tracker)")
        out.append(W)
        out.append("    {")
        if kind == "Tuple":
            out.append("        if (value is null) { writer.GetSpanRef(1) = 0; return; }")
            out.append("        writer.GetSpanRef(1) = 1;")
        else:
            out.append("        if (FixedSize >= 0) { WriteFixed(ref writer.GetSpanRef(FixedSize), in value, TWriter.IsHostLittleEndian); return; }")
        for i, (t, f, it) in enumerate(zip(ts, fs, items)):
            out.append(f"        {t} v{i} = value.{it};")
            out.append(f"        {f}.Write(ref writer, in v{i}, ref tracker);")
        out.append("    }")
        out.append("")
        out.append("    [MethodImpl(MethodImplOptions.AggressiveInlining)]")
        out.append(f"    public static {target} Read<TReader, TTracker, TGuard>(ref TReader reader, ref TTracker tracker, ref TGuard guard)")
        out.append(R)
        out.append("    {")
        if kind == "Tuple":
            out.append("        if (reader.GetSpanRef(1) == 0) return null;")
        else:
            out.append("        if (FixedSize >= 0) return ReadFixed(in reader.GetSpanRef(FixedSize), TReader.IsHostLittleEndian);")
        for i, (t, f) in enumerate(zip(ts, fs)):
            out.append(f"        {t} v{i} = {f}.Read(ref reader, ref tracker, ref guard);")
        args = ", ".join(f"v{i}" for i in range(len(ts)))
        out.append(f"        return new {tt}({args});")
        out.append("    }")
        if kind == "ValueTuple":
            out.append("")
            out.append("    public static int MinWireSize => " + " + ".join(f"{f}.MinWireSize" for f in fs) + ";")
            out.append("")
            out.append("    /// <summary>全要素が固定長なら、その合計。</summary>")
            out.append("    public static int FixedSize")
            out.append("    {")
            out.append("        [MethodImpl(MethodImplOptions.AggressiveInlining)]")
            out.append("        get => " + " && ".join(f"{f}.FixedSize >= 0" for f in fs) + " ? " + " + ".join(f"{f}.FixedSize" for f in fs) + " : -1;")
            out.append("    }")
            out.append("")
            out.append("    public static bool IsRawLayout")
            out.append("    {")
            out.append("        [MethodImpl(MethodImplOptions.AggressiveInlining)]")
            out.append("        get => Layout.IsRaw;")
            out.append("    }")
            out.append("")
            out.append("    public static int RawPrefixSize")
            out.append("    {")
            out.append("        [MethodImpl(MethodImplOptions.AggressiveInlining)]")
            out.append("        get => Layout.IsPrefixRaw ? FixedSize : -1;")
            out.append("    }")
            out.append("")
            # 各要素の位置(ワイヤ上)は前の要素の固定長の合計
            def offset(i):
                return " + ".join(f"{fs[j]}.FixedSize" for j in range(i)) if i > 0 else "0"
            out.append("    [MethodImpl(MethodImplOptions.AggressiveInlining)]")
            out.append(f"    public static void WriteFixed(ref byte destination, scoped in {target} value, bool littleEndian)")
            out.append("    {")
            out.append(f"        if (littleEndian && Layout.IsRaw) {{ Unsafe.WriteUnaligned(ref destination, value); return; }}")
            out.append(f"        if (littleEndian && Layout.IsPrefixRaw) {{ ApexWire.CopySmall(ref destination, ref Unsafe.As<{tt}, byte>(ref Unsafe.AsRef(in value)), FixedSize); return; }}")
            for i, (t, f, it) in enumerate(zip(ts, fs, items)):
                out.append(f"        {f}.WriteFixed(ref Unsafe.Add(ref destination, {offset(i)}), value.{it}, littleEndian);")
            out.append("    }")
            out.append("")
            out.append("    [MethodImpl(MethodImplOptions.AggressiveInlining)]")
            out.append(f"    public static {target} ReadFixed(ref readonly byte source, bool littleEndian)")
            out.append("    {")
            out.append(f"        if (littleEndian && Layout.IsRaw) return Unsafe.ReadUnaligned<{tt}>(in source);")
            out.append(f"        if (littleEndian && Layout.IsPrefixRaw) return ApexWire.ReadPrefix<{tt}>(in source, FixedSize);")
            for i, (t, f) in enumerate(zip(ts, fs)):
                out.append(f"        {t} v{i} = {f}.ReadFixed(in Unsafe.Add(ref Unsafe.AsRef(in source), {offset(i)}), littleEndian);")
            out.append(f"        return new {tt}({args});")
            out.append("    }")
            out.append("")
            out.append("    /// <summary>")
            out.append("    /// LE 機のメモリ表現がワイヤ形式と一致するか(要素がすべて一致し、すき間なく宣言順に並ぶ)。型ごとに 1 回だけ調べる。")
            out.append("    /// IsPrefixRaw は、後ろに詰め物があってもよい(先頭 FixedSize バイトが一致する)。")
            out.append("    /// </summary>")
            out.append("    private static class Layout")
            out.append("    {")
            out.append("        public static readonly bool IsPrefixRaw = Compute();")
            out.append("")
            out.append("        public static readonly bool IsRaw = IsPrefixRaw && Unsafe.SizeOf<" + tt + ">() == FixedSize;")
            out.append("")
            out.append("        private static bool Compute()")
            out.append("        {")
            out.append("            if (FixedSize < 0 || Unsafe.SizeOf<" + tt + ">() < FixedSize) return false;")
            out.append("            if (!(" + " && ".join(f"{f}.IsRawLayout" for f in fs) + ")) return false;")
            out.append(f"            var probe = default({tt});")
            out.append(f"            ref byte start = ref Unsafe.As<{tt}, byte>(ref probe);")
            for i, (t, f, it) in enumerate(zip(ts, fs, items)):
                out.append(f"            if (Unsafe.ByteOffset(ref start, ref Unsafe.As<{t}, byte>(ref probe.{it})) != (nint)({offset(i)})) return false;")
            out.append("            return true;")
            out.append("        }")
            out.append("    }")
        out.append("}")
        out.append("")
open(sys.argv[1], "w", encoding="utf-8", newline="\n").write("\n".join(out))
